// why: the sidebar, llms.txt and the sitemap read the docs pages from disk on every build, so adding,
// moving or renaming a page needs no list to be edited. A page's place comes from its folder (one
// of `sections`) and its frontmatter `sidebar.order`.
import { execFileSync } from "node:child_process";
import { readdirSync, readFileSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";

import { parse } from "yaml";

const ROOT = fileURLToPath(new URL("../..", import.meta.url));
const CONTENT = join(ROOT, "src/content/docs");

// why: the sidebar's groups, in order; llms.txt follows the same order and has one file per group.
export const sections = [
  { label: "Introduction", directory: "docs/introduction" },
  { label: "Get started", directory: "docs/getting-started" },
  { label: "Concepts", directory: "docs/concepts" },
  { label: "Use devices", directory: "docs/using-devices" },
  { label: "Run a worker", directory: "docs/worker" },
  { label: "Run a fleet", directory: "docs/gateway" },
  { label: "Troubleshooting", directory: "docs/troubleshooting" },
  { label: "Reference", directory: "docs/reference" },
];

type Page = { id: string; file: string; order: number };

const inSection = (id: string, directory: string) =>
  id === directory || id.startsWith(`${directory}/`);

const walk = (dir: string): string[] =>
  readdirSync(dir, { withFileTypes: true }).flatMap((entry) =>
    entry.isDirectory() ? walk(join(dir, entry.name)) : [join(dir, entry.name)],
  );

export function docPages(): Page[] {
  return walk(CONTENT)
    .filter((file) => /\.mdx?$/.test(file))
    .map((file) => {
      const id = relative(CONTENT, file)
        .replace(/\.mdx?$/, "")
        .replace(/(^|\/)index$/, "");
      const front = /^---\n([\s\S]*?)\n---/.exec(readFileSync(file, "utf8"))?.[1] ?? "";
      const order = (parse(front) as { sidebar?: { order?: number } } | null)?.sidebar?.order;
      return { id, file: relative(ROOT, file), order: order ?? Number.MAX_SAFE_INTEGER };
    });
}

// why: llms.txt sorts pages by path unless told otherwise; this gives it the sidebar's order.
export function readingOrder(pages = docPages()): string[] {
  const rank = (id: string) => {
    const index = sections.findIndex((s) => inSection(id, s.directory));
    return index === -1 ? sections.length : index;
  };
  return pages
    .toSorted((a, b) => rank(a.id) - rank(b.id) || a.order - b.order || a.id.localeCompare(b.id))
    .map((p) => p.id);
}

// why: autogenerated groups only take folders, so a page outside them is linked on its own.
export const topLevelPages = (pages = docPages()) =>
  readingOrder(pages).filter((id) => !sections.some((s) => inSection(id, s.directory)));

export function sourcesOf(path: string, pages = docPages()): string[] {
  const id = path.replace(/^\/|\/$/g, "");
  if (id === "") return ["src/pages/index.astro", "src/site/content.ts"];
  const page = pages.find((p) => p.id === id);
  return page ? [page.file] : [];
}

let shallow: boolean | undefined;

// why: no date beats a wrong one: a shallow clone would give every page its one commit's date,
// and a build outside a repository has none.
export function lastModified(files: string[]): string | undefined {
  if (files.length === 0) return undefined;
  const git = (args: string[]) =>
    execFileSync("git", args, { cwd: ROOT, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim();
  try {
    shallow ??= git(["rev-parse", "--is-shallow-repository"]) === "true";
    if (shallow) return undefined;
    return git(["log", "-1", "--format=%cI", "--", ...files]) || undefined;
  } catch {
    return undefined;
  }
}
